//! `edel image deps` (roadmap M8.10b): which of the images' packages come
//! from Alpine's community repository, whose fixes stop at the next stable
//! branch, about six months, while main's run two years; for those we
//! backport fixes ourselves (ADR-003). It reads the images' package lists
//! (`out/IMAGE.packages`, one `name-version` a line), asks `apk policy`
//! where each comes from, and prints `docs/backports.md`, which CI diffs.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

/// Prints the backports list of the package lists `lists`, asking the apk
/// of this system, which must use the images' Alpine branch (CI's build
/// container).
pub fn deps(lists: &[PathBuf]) -> Result<()> {
    let mut images: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for list in lists {
        let text = fs::read_to_string(list)
            .with_context(|| format!("could not read the package list {}", list.display()))?;
        let image = image_name(list);
        for name in text.lines().filter_map(package_name) {
            images
                .entry(name.to_string())
                .or_default()
                .insert(image.clone());
        }
    }
    if images.is_empty() {
        bail!(
            "the package lists name no package; give the images' out/IMAGE.packages files, which edel image build writes"
        );
    }
    let out = Command::new("apk")
        .arg("policy")
        .args(images.keys())
        .output()
        .context("could not run apk policy; run edel image deps where apk uses the images' Alpine branch, as CI's build container does")?;
    if !out.status.success() {
        bail!(
            "apk policy failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    let community = community(&String::from_utf8_lossy(&out.stdout));
    images.retain(|name, _| community.contains(name));
    print!("{}", markdown(&images));
    Ok(())
}

/// The image a list names: its file name without `.packages`.
fn image_name(list: &Path) -> String {
    let name = list.file_name().unwrap_or_default().to_string_lossy();
    name.strip_suffix(".packages").unwrap_or(&name).to_string()
}

/// The package of a `name-version` line: an apk version ends in `-rN`, so
/// the name is all but the last two dash-separated fields.
fn package_name(line: &str) -> Option<&str> {
    let line = line.trim();
    let release = line.rfind('-')?;
    let version = line[..release].rfind('-')?;
    (version > 0).then(|| &line[..version])
}

/// The packages `apk policy` says come only from a `community` repository:
/// each `NAME policy:` heading, then its versions, each followed by the
/// places that have it (the installed database or a repository's URL).
fn community(policy: &str) -> BTreeSet<String> {
    let mut repos: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
    let mut current = None;
    for line in policy.lines() {
        if let Some(name) = line
            .strip_suffix(" policy:")
            .filter(|_| !line.starts_with(' '))
        {
            current = Some(name);
        } else if let (Some(name), Some(url)) = (current, line.strip_prefix("    ")) {
            if url.contains("://") {
                let repo = url.trim_end_matches('/').rsplit('/').next().unwrap_or("");
                repos.entry(name).or_default().insert(repo);
            }
        }
    }
    repos
        .into_iter()
        .filter(|(_, r)| r.contains("community") && !r.contains("main"))
        .map(|(name, _)| name.to_string())
        .collect()
}

/// `docs/backports.md` for the community packages and the images each is in.
fn markdown(packages: &BTreeMap<String, BTreeSet<String>>) -> String {
    let mut out = String::from(
        "# Backports\n\n\
         Generated by `edel image deps` from the images' package lists (roadmap M8.10b): do not edit it by hand. CI's build makes it again and fails when it differs; copy the file from the run's summary.\n\n\
         Alpine's main repository gets fixes for about two years, its community repository only until the next stable branch, about six months. For every base package below, which comes from community, we backport security fixes ourselves for the full two years of a base release (ADR-003). Keeping the base small keeps this list short.\n\n",
    );
    out.push_str(&format!(
        "Packages from community: {}.\n\n| Package | Images |\n|---|---|\n",
        packages.len()
    ));
    for (name, images) in packages {
        let images: Vec<&str> = images.iter().map(String::as_str).collect();
        out.push_str(&format!("| `{name}` | {} |\n", images.join(", ")));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_line_names_its_package() {
        assert_eq!(package_name("musl-1.2.5-r10"), Some("musl"));
        assert_eq!(package_name("xz-libs-5.8.1-r0"), Some("xz-libs"));
        assert_eq!(package_name("broken"), None);
        assert_eq!(package_name(""), None);
    }

    #[test]
    fn only_packages_found_in_community_alone_count() {
        let policy = "busybox policy:\n  1.37.0-r31:\n    lib/apk/db/installed\n    https://dl-cdn.alpinelinux.org/alpine/v3.24/main\n\
                      foot policy:\n  1.27.0-r0:\n    https://dl-cdn.alpinelinux.org/alpine/v3.24/community\n\
                      gone policy:\n";
        assert_eq!(community(policy), BTreeSet::from(["foot".to_string()]));
    }

    #[test]
    fn the_list_names_each_package_and_its_images() {
        let packages = BTreeMap::from([(
            "foot".to_string(),
            BTreeSet::from([
                "edel-x86_64".to_string(),
                "edel-container-x86_64".to_string(),
            ]),
        )]);
        let md = markdown(&packages);
        assert!(md.starts_with("# Backports\n"));
        assert!(md.contains("Packages from community: 1."));
        assert!(md.ends_with("| `foot` | edel-container-x86_64, edel-x86_64 |\n"));
    }
}
